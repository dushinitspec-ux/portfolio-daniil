import type { Metadata } from "next";

import { routing, type Locale } from "@/i18n/routing";
import { site } from "@/lib/site";

const OG_LOCALES: Record<Locale, string> = {
  en: "en_US",
  ru: "ru_RU",
  tr: "tr_TR",
  de: "de_DE",
};

/** Canonical URL, hreflang alternates and Open Graph tags for one page in one language. */
export function pageMetadata(options: {
  locale: Locale;
  path: string; // "" for the home page, "/projects" etc.
  title: string;
  description: string;
  image?: string; // generated by scripts/build-og.mjs; defaults to the site-wide card
}): Metadata {
  const { locale, path, title, description } = options;
  const image = options.image ?? `/og/${locale}/default.png`;
  const images = [{ url: image, width: 1200, height: 630, alt: title }];
  const languages: Record<string, string> = Object.fromEntries(
    routing.locales.map((l) => [l, `/${l}${path}`]),
  );
  languages["x-default"] = `/${routing.defaultLocale}${path}`;

  return {
    title,
    description,
    alternates: { canonical: `/${locale}${path}`, languages },
    openGraph: {
      type: "website",
      siteName: site.name,
      title,
      description,
      url: `/${locale}${path}`,
      locale: OG_LOCALES[locale],
      alternateLocale: routing.locales.filter((l) => l !== locale).map((l) => OG_LOCALES[l]),
      images,
    },
    twitter: { card: "summary_large_image", title, description, images },
  };
}
